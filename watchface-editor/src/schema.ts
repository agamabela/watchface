export const SCHEMA_VERSION = 1 as const

export type DevicePreset = 'redmi-watch-5-lite' | 'redmi-watch-5' | 'redmi-watch-6' | 'custom'
export type ElementType = 'text' | 'digitalTime' | 'analogTime' | 'widget' | 'shape' | 'image'
export type WidgetMetric = 'steps' | 'battery' | 'heartRate' | 'calories' | 'date' | 'weather'

export interface Device {
  preset: DevicePreset
  name: string
  width: number
  height: number
  cornerRadius: number
  roundMask: boolean
}

export interface Theme {
  background: string
  primary: string
  secondary: string
  accent: string
}

export interface ElementBase {
  id: string
  type: ElementType
  name: string
  x: number
  y: number
  width: number
  height: number
  rotation: number
  opacity: number
  visible: boolean
  locked: boolean
  zIndex: number
  showInAOD: boolean
}

export interface TextStyle {
  fontFamily: string
  fontSize: number
  fontWeight: number
  color: string
  letterSpacing: number
  lineHeight: number
  textAlign: 'left' | 'center' | 'right'
  glow?: boolean
  glowColor?: string
}

export interface TextElement extends ElementBase {
  type: 'text'
  text: string
  style: TextStyle
}

export interface DigitalTimeElement extends ElementBase {
  type: 'digitalTime'
  format: '24h' | '12h'
  showSeconds: boolean
  leadingZero: boolean
  separator: ':' | 'none' | 'custom'
  customSeparator: string
  style: TextStyle
}

export interface AnalogTimeElement extends ElementBase {
  type: 'analogTime'
  faceColor: string
  handColor: string
  secondHandColor: string
  showSecondHand: boolean
}

export interface WidgetElement extends ElementBase {
  type: 'widget'
  metric: WidgetMetric
  icon: string
  label: string
  text: string
  showIcon?: boolean
  showLabel?: boolean
  style: TextStyle
}

export interface ShapeElement extends ElementBase {
  type: 'shape'
  shapeType: 'rect' | 'divider' | 'progressBar' | 'badge'
  fill: string
  stroke?: string
  strokeWidth?: number
  cornerRadius?: number
  progress?: number // 0 to 100 for progressBar
}

export interface ImageElement extends ElementBase {
  type: 'image'
  src: string
  fit?: 'cover' | 'contain'
}

export type WatchElement = TextElement | DigitalTimeElement | AnalogTimeElement | WidgetElement | ShapeElement | ImageElement

export interface Project {
  schemaVersion: typeof SCHEMA_VERSION
  name: string
  device: Device
  theme: Theme
  backgroundImage?: string
  backgroundDarken?: number // 0-100 percentage overlay
  backgroundBlur?: number // 0-20 blur in px
  elements: WatchElement[]
}

